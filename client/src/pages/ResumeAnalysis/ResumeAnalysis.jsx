import { useEffect, useState } from "react";
import { useParams } from "react-router-dom";
import {
  BrainCircuit,
  Check,
  Lightbulb,
  ShieldCheck,
  TrendingUp,
  X,
} from "lucide-react";
import {
  BarChart,
  Bar,
  ResponsiveContainer,
  XAxis,
  YAxis,
  Tooltip,
} from "recharts";
import api from "../../services/api";
import {
  EmptyState,
  ErrorState,
  Loading,
} from "../../components/common/States";
export function ResumeAnalysis() {
  const { id } = useParams();
  const [analysis, setAnalysis] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");
  useEffect(() => {
    api
      .get(`/api/resume/${id}/analysis`)
      .then(({ data }) => setAnalysis(data.analysis))
      .catch((err) =>
        setError(
          err.response?.data?.message || "Unable to fetch resume analysis",
        ),
      )
      .finally(() => setLoading(false));
  }, [id]);
  if (loading) return <Loading label="Loading analysis" />;
  if (error)
    return error === "Resume analysis not found" ? (
      <EmptyState
        title="Analysis not ready yet."
        description="Analyze this resume first, then your preparation signals will appear here."
      />
    ) : (
      <ErrorState message={error} />
    );
  if (!analysis)
    return (
      <EmptyState
        title="No analysis available."
        description="There is no saved analysis for this resume yet."
      />
    );
  const chartData = [{ name: "Score", value: analysis.overallScore }];
  return (
    <>
      <div className="mb-9 flex flex-col items-start justify-between gap-5 min-[521px]:flex-row min-[521px]:items-center">
        <div>
          <span className="inline-flex items-center gap-[7px] font-mono text-[11px] tracking-[0.04em] text-muted uppercase">
            <BrainCircuit size={14} /> AI resume analysis
          </span>
          <h1 className="my-[10px] font-display text-[28px] tracking-[-0.05em] sm:text-[32px]">Your resume, decoded.</h1>
          <p className="text-sm text-muted">A clear read on what is working and where to focus next.</p>
        </div>
        <span className="rounded-full bg-[#e7ece6] px-3 py-2 font-mono text-[10px] text-[#5b7869]">{analysis.model}</span>
      </div>
      <section className="grid gap-4 min-[801px]:grid-cols-[1fr_1.35fr]">
        <div className="relative flex min-h-[210px] justify-between overflow-hidden bg-navy p-7 text-white sm:min-h-[230px]">
          <div>
            <span className="inline-flex items-center gap-[7px] font-mono text-[11px] tracking-[0.04em] text-[#9ab0b1] uppercase">Overall score</span>
            <strong className="mt-[25px] block font-display text-[48px] font-bold tracking-[-0.08em] sm:text-[58px]">
              {analysis.overallScore}
              <small className="ml-1.5 font-mono text-[13px] tracking-normal text-[#95acad]">/100</small>
            </strong>
            <span className="flex items-center gap-[5px] text-[11px] text-[#a5c8ac]">
              <TrendingUp size={15} /> Your starting point
            </span>
          </div>
          <div className="h-40 w-[110px] sm:w-[150px]">
            <ResponsiveContainer width="100%" height="100%">
              <BarChart data={chartData}>
                <XAxis dataKey="name" hide />
                <YAxis domain={[0, 100]} hide />
                <Tooltip cursor={false} />
              </BarChart>
            </ResponsiveContainer>
          </div>
        </div>
        <div className="flex flex-col justify-center border border-line bg-surface p-[18px] sm:p-[27px]">
          <span className="inline-flex items-center gap-[7px] font-mono text-[11px] tracking-[0.04em] text-muted uppercase">Executive summary</span>
          <h2 className="my-4 max-w-[530px] font-display text-xl leading-[1.4]">{analysis.summary}</h2>
          <p className="text-xs text-muted">Generated by {analysis.model} and saved to your workspace.</p>
        </div>
      </section>
      <div className="mt-4 grid grid-cols-1 gap-3 min-[801px]:grid-cols-2">
        <AnalysisList
          title="Strengths"
          icon={Check}
          items={analysis.strengths}
          tone="positive"
        />
        <AnalysisList
          title="Weaknesses"
          icon={X}
          items={analysis.weaknesses}
          tone="negative"
        />
        <AnalysisList
          title="Missing skills"
          icon={Lightbulb}
          items={analysis.missingSkills}
          tone="warning"
        />
        <AnalysisList
          title="Suggestions"
          icon={TrendingUp}
          items={analysis.suggestions}
          tone="neutral"
        />
      </div>
      <section className="mt-4 grid items-start gap-6 border border-line bg-surface p-[18px] sm:p-[27px] min-[801px]:grid-cols-[1fr_2fr] min-[801px]:gap-10">
        <div>
          <span className="inline-flex items-center gap-[7px] font-mono text-[11px] tracking-[0.04em] text-muted uppercase">
            <ShieldCheck size={14} /> ATS feedback
          </span>
          <h2 className="mt-3 font-display text-[19px]">Make it easier to find you.</h2>
        </div>
        <p className="text-[13px] leading-[1.8] text-muted">{analysis.atsFeedback}</p>
      </section>
    </>
  );
}
const analysisToneClasses = {
  positive: "bg-[#e0eee2] text-[#579264]",
  negative: "bg-[#f9dfdc] text-[#c55b51]",
  warning: "bg-[#f8ebd1] text-[#a77a30]",
  neutral: "bg-[#e6e7f0] text-[#5d668c]",
};

function AnalysisList({ title, icon: Icon, items = [], tone }) {
  return (
    <article className="min-h-[170px] border border-line bg-surface p-[21px]">
      <div className="flex items-center gap-[9px]">
        <span className={`flex size-[25px] shrink-0 items-center justify-center rounded-full ${analysisToneClasses[tone] || analysisToneClasses.neutral}`}>
          <Icon size={16} />
        </span>
        <h3 className="font-display text-sm">{title}</h3>
        <span className="ml-auto font-mono text-[11px] text-muted">{items.length}</span>
      </div>
      {items.length ? (
        <ul className="mt-[19px] grid list-none gap-[9px] p-0">
          {items.map((item) => (
            <li className="relative pl-[14px] text-xs leading-[1.5] text-muted before:absolute before:top-[7px] before:left-0 before:size-1 before:rounded-full before:bg-current before:content-['']" key={item}>{item}</li>
          ))}
        </ul>
      ) : (
        <p className="mt-5 text-xs text-muted">No signals here yet.</p>
      )}
    </article>
  );
}
